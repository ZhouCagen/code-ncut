import { test, expect } from '@playwright/test'

test('ElevenLabs 设置、连接、生成与播放下载', async ({ page, request, context }) => {
  const external: string[] = []
  page.on('request', req => { if (new URL(req.url()).port === '18083') external.push(req.url()) })
  await request.put('/api/settings', { data: { text: { provider: 'mock' }, music: { provider: 'mock' } } })
  await page.goto('/settings')
  await page.getByLabel('音乐生成服务商', { exact: true }).selectOption('elevenlabs')
  await expect(page.getByLabel('ElevenLabs 音乐模型', { exact: true })).toHaveValue('music_v1')
  await page.getByLabel('ElevenLabs API Key', { exact: true }).fill('fixture-elevenlabs-secret')
  await page.getByRole('button', { name: '保存并测试密钥', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'ElevenLabs Key 与音乐编排接口连接成功' })).toBeVisible({ timeout: 15000 })
  await expect(page.getByLabel('ElevenLabs API Key', { exact: true })).toHaveValue('')
  expect(await (await request.get('/api/settings')).text()).not.toContain('fixture-elevenlabs-secret')
  expect(JSON.stringify(await context.storageState())).not.toContain('fixture-elevenlabs-secret')
  await page.screenshot({ path: 'test-results/elevenlabs-settings.png', fullPage: true })
  await page.getByRole('button', { name: '生成测试音乐 · 可能收费', exact: true }).click()
  await expect(page.locator('audio')).toHaveCount(1, { timeout: 15000 })
  await expect(page.getByText('ElevenLabs 音频', { exact: false })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载 WAV' }).click()
  expect((await download).suggestedFilename()).toMatch(/\.wav$/)
  expect(external).toEqual([])
  const versions = await (await request.get('/api/versions')).json()
  const created = versions.filter((v: { provider: string }) => v.provider === 'elevenlabs')
  for (const v of created) await request.delete('/api/projects/' + v.projectId)
  await request.put('/api/settings', { data: { music: { provider: 'elevenlabs', clearApiKey: true } } })
  await request.put('/api/settings', { data: { music: { provider: 'mock' } } })
})
