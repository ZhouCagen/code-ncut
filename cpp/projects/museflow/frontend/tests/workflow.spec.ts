import { test, expect } from '@playwright/test'
test('场景 → 设计稿 → 校验 → 生成 → 播放下载 → 重载 → 独立新版本', async ({ page }) => {
  const exceptions: string[] = []
  page.on('pageerror', error => exceptions.push(error.message))
  await page.goto('/studio')
  await expect(page.getByText('模拟模式 · 不产生 API 费用')).toBeVisible()
  await page.getByLabel('场景描述').fill('黄昏的森林，旅人找到了回家的路。')
  await page.getByRole('button', { name: 'AI 生成音乐设计稿' }).click()
  await expect(page.getByLabel('作品标题')).toBeVisible()
  await page.getByLabel('作品标题').fill('森林归途 · E2E')
  await page.getByLabel('BPM', { exact: true }).fill('104')
  await page.getByLabel('开始（秒）').nth(1).fill('10')
  await expect(page.getByText('展开 · 远行：时间段重叠')).toBeVisible()
  await expect(page.getByRole('button', { name: '生成 30 秒试听 · 模拟' })).toBeDisabled()
  await page.getByLabel('开始（秒）').nth(1).fill('15')
  await page.screenshot({ path: 'test-results/studio-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '生成 30 秒试听 · 模拟' }).click()
  await expect(page.getByText('作品已保存', { exact: true })).toBeVisible({ timeout: 15000 })
  const player = page.locator('audio')
  await expect(player).toBeVisible()
  await player.evaluate(async (audio: HTMLAudioElement) => { await audio.play() })
  await expect.poll(() => player.evaluate((audio: HTMLAudioElement) => audio.currentTime)).toBeGreaterThan(0)
  await player.evaluate((audio: HTMLAudioElement) => audio.pause())
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '↓ 下载 WAV' }).click()
  expect((await download).suggestedFilename()).toMatch(/^museflow-.*\.wav$/)
  await page.getByRole('link', { name: '音乐项目', exact: true }).click()
  await expect(page.getByRole('heading', { name: '森林归途 · E2E' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '打开设计稿 →' }).click()
  await expect(page.getByLabel('BPM', { exact: true })).toHaveValue('104')
  await page.getByLabel('BPM', { exact: true }).fill('116')
  await page.getByRole('button', { name: '生成完整歌曲 · 模拟' }).click()
  await expect(page.getByText('作品已保存', { exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByRole('link', { name: '作品库', exact: true }).click()
  await expect(page.locator('audio')).toHaveCount(2)
  await page.getByLabel('搜索作品').fill('不存在的名字')
  await expect(page.getByText('没有匹配的作品')).toBeVisible()
  await page.getByLabel('搜索作品').fill('森林')
  await expect(page.locator('audio')).toHaveCount(2)
  await page.getByRole('link', { name: '音乐项目', exact: true }).click()
  await page.getByRole('button', { name: '打开设计稿 →' }).click()
  await page.getByRole('button', { name: '生成完整歌曲 · 模拟' }).click()
  await expect(page.getByText('模拟音乐生成', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '作品库', exact: true }).click()
  await expect(page.locator('audio')).toHaveCount(3, { timeout: 15000 })
  expect(exceptions).toEqual([])
})
