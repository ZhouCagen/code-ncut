test('版本分支、A/B 切换、评分、项目导出与删除保护', async ({ page, request }) => {
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/studio')
  await page.getByRole('button', { name: 'AI 生成音乐设计稿' }).click()
  await page.getByLabel('作品标题').fill('分支比较 · E2E')
  await page.getByRole('button', { name: '生成完整歌曲 · 模拟' }).click()
  await expect(page.getByText('作品已保存', { exact: true })).toBeVisible({ timeout: 15000 })
  const projects = await (await request.get('/api/projects')).json()
  const project = projects.find((p: { name: string }) => p.name === '分支比较 · E2E')
  const [root] = await (await request.get(`/api/projects/${project.id}/versions`)).json()
  await page.getByRole('link', { name: '作品库', exact: true }).click()
  await page.getByLabel('搜索作品').fill('分支比较')
  await page.getByRole('button', { name: '从此版本创建分支' }).click()
  await expect(page.getByText(`分支草稿 · 父版本 ${root.id.slice(0, 8)}`)).toBeVisible()
  await page.getByLabel('BPM', { exact: true }).fill('116')
  await page.getByLabel('严格时长', { exact: true }).check()
  await page.getByRole('button', { name: '生成完整歌曲 · 模拟' }).click()
  await expect(page.getByText('作品已保存', { exact: true })).toBeVisible({ timeout: 15000 })
  const [child] = await (await request.get(`/api/projects/${project.id}/versions`)).json()
  expect(child.parentVersionId).toBe(root.id)
  await page.getByRole('link', { name: '版本对比', exact: true }).click()
  await page.getByLabel('筛选项目').selectOption(project.id)
  await expect(page.locator('.version-tree li')).toHaveCount(2)
  await expect(page.locator('.diff-table')).toContainText('116')
  await page.getByLabel('对比 A 音频').evaluate((audio: HTMLAudioElement) => { audio.currentTime = 1 })
  await page.getByRole('button', { name: '播放当前版本', exact: true }).click()
  await page.getByRole('button', { name: '切换到 B', exact: true }).click()
  await expect.poll(() => page.getByLabel('对比 B 音频').evaluate((audio: HTMLAudioElement) => audio.currentTime)).toBeGreaterThanOrEqual(1)
  expect(await page.getByLabel('对比 A 音频').evaluate((audio: HTMLAudioElement) => audio.paused)).toBe(true)
  await page.getByLabel('循环播放当前版本').check()
  expect(await page.getByLabel('对比 B 音频').evaluate((audio: HTMLAudioElement) => audio.loop)).toBe(true)
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  const metadata = page.locator('.ab-metadata section').first()
  await metadata.locator('summary').click()
  await metadata.getByLabel('版本评分').selectOption('5')
  await metadata.getByLabel('版本备注').fill('适合片尾，保留这个版本。')
  await metadata.getByRole('button', { name: '保存评价' }).click()
  await expect(metadata.getByRole('status')).toHaveText('评价已保存')
  await page.screenshot({ path: 'test-results/version-compare-desktop.png', fullPage: true })
  await page.reload()
  await page.getByLabel('筛选项目').selectOption(project.id)
  expect((await (await request.get(`/api/versions/${child.id}`)).json()).rating).toBe(5)
  await page.getByRole('link', { name: '音乐项目', exact: true }).click()
  await page.getByLabel('搜索项目').fill('分支比较')
  await page.getByRole('button', { name: '重命名', exact: true }).click()
  await page.getByLabel('项目新名称').fill('短片配乐项目')
  await page.getByRole('button', { name: '保存名称' }).click()
  await page.getByLabel('搜索项目').fill('短片配乐')
  await expect(page.getByRole('heading', { name: '短片配乐项目' })).toBeVisible()
  await page.getByRole('button', { name: '生成记录', exact: true }).click()
  await expect(page.locator('.history-list li')).toHaveCount(2)
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '导出设计与记录' }).click()
  expect((await download).suggestedFilename()).toMatch(/^museflow-project-.*\.json$/)
  await page.getByRole('link', { name: '作品库', exact: true }).click()
  await page.getByLabel('搜索作品').fill('分支比较')
  await page.locator(`article[data-version-id="${root.id}"]`).getByRole('button', { name: '删除作品' }).click()
  await expect(page.getByRole('alert')).toContainText('仍有分支作品')
  await page.locator(`article[data-version-id="${child.id}"]`).getByRole('button', { name: '删除作品' }).click()
  await expect(page.locator(`article[data-version-id="${child.id}"]`)).toHaveCount(0)
  await expect(page.locator(`article[data-version-id="${root.id}"]`)).toHaveCount(1)
})
